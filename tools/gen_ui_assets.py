#!/usr/bin/env python3
"""
MC Music - UI asset generator.

Generates every texture the mod's modern UI needs, so the look is fully
reproducible and nothing has to be hand-drawn:

  assets/mcmusic/textures/gui/font.png     high resolution glyph atlas (4x AA)
  assets/mcmusic/gui/font.txt              glyph metrics for that atlas
  assets/mcmusic/textures/gui/icons.png    24 vector style icons, white, tintable
  assets/mcmusic/textures/gui/corner.png   anti aliased rounded corner mask
  assets/mcmusic/icon.png                  mod icon

Usage:  python3 tools/gen_ui_assets.py
Requires: pillow   (pip install pillow)
"""

from __future__ import annotations

import os
import sys
from PIL import Image, ImageDraw, ImageFont, ImageFilter

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ASSETS = os.path.join(ROOT, "src", "main", "resources", "assets", "mcmusic")
TEX = os.path.join(ASSETS, "textures", "gui")

FONT_CANDIDATES = [
    "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf",
    "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf",
    "/Library/Fonts/Arial.ttf",
    "C:/Windows/Fonts/segoeui.ttf",
]

# Glyphs that are packed into the atlas. ASCII + Latin-1 + a few punctuation
# marks that show up in music titles.
SPECIAL = "\u2026\u2013\u2014\u201c\u201d\u201e\u2018\u2019\u2022\u2605\u2606\u2665\u266a\u266b\u00b7\u20ac"
CHARS = [chr(c) for c in range(32, 127)] + [chr(c) for c in range(160, 256)] + list(SPECIAL)


def find_font() -> str:
    for path in FONT_CANDIDATES:
        if os.path.exists(path):
            return path
    sys.exit("No TrueType font found - install DejaVu fonts (fonts-dejavu) or edit FONT_CANDIDATES.")


# ---------------------------------------------------------------------------
# Font atlas
# ---------------------------------------------------------------------------
GLYPH_PX = 40          # render size of the source glyphs
BASELINE = 40          # baseline inside every cell
COLS = 16


def build_font() -> None:
    font = ImageFont.truetype(find_font(), GLYPH_PX)

    # Ink bounds relative to the baseline, so the blit quads stay tight.
    left, top, right, bottom = 0, 0, 0, 0
    for ch in CHARS:
        if ch == " ":
            continue
        l, t, r, b = font.getbbox(ch, anchor="ls")
        left = min(left, l)
        top = min(top, t)
        right = max(right, r)
        bottom = max(bottom, b)

    pad = 2
    cell_w = right - left + pad * 2
    cell_h = bottom - top + pad * 2
    rows = (len(CHARS) + COLS - 1) // COLS

    # Power of two atlas so the GPU can generate mipmaps.
    def pot(v: int) -> int:
        p = 1
        while p < v:
            p *= 2
        return p

    atlas_w, atlas_h = pot(cell_w * COLS), pot(cell_h * rows)
    image = Image.new("RGBA", (atlas_w, atlas_h), (255, 255, 255, 0))
    draw = ImageDraw.Draw(image)

    metrics = []
    for index, ch in enumerate(CHARS):
        col, row = index % COLS, index // COLS
        ox, oy = col * cell_w, row * cell_h
        # Draw the glyph so that (ox - left + pad, oy - top + pad) is its ink origin
        # baseline placed so that the global ink bounds sit inside the cell
        draw.text((ox + pad - left, oy + pad - top), ch,
                  font=font, fill=(255, 255, 255, 255), anchor="ls")
        advance = font.getlength(ch)
        metrics.append((ord(ch), round(advance, 2), col, row))

    image.save(os.path.join(TEX, "font.png"))

    write_font_java(cell_w, cell_h, atlas_w, atlas_h, left, top, pad, metrics)

    with open(os.path.join(ASSETS, "gui", "font.txt"), "w", encoding="utf-8") as fh:
        fh.write("# MC Music glyph metrics - generated by tools/gen_ui_assets.py\n")
        fh.write("cellWidth=%d\n" % cell_w)
        fh.write("cellHeight=%d\n" % cell_h)
        fh.write("atlasWidth=%d\n" % atlas_w)
        fh.write("atlasHeight=%d\n" % atlas_h)
        fh.write("columns=%d\n" % COLS)
        fh.write("glyphSize=%d\n" % GLYPH_PX)
        fh.write("baseline=%d\n" % BASELINE)
        fh.write("inkLeft=%d\n" % left)
        fh.write("inkTop=%d\n" % top)
        fh.write("inkBottom=%d\n" % bottom)
        fh.write("inkRight=%d\n" % right)
        fh.write("pad=%d\n" % pad)
        # Offset of a cell's top left corner relative to (penX, baselineY)
        fh.write("originX=%d\n" % (-(pad - left)))
        fh.write("originY=%d\n" % (-(pad - top)))
        fh.write("# codepoint advance column row\n")
        for code, advance, col, row in metrics:
            fh.write("%d %.2f %d %d\n" % (code, advance, col, row))

    print("font.png      %dx%d  (%d glyphs, %dx%d cells)" % (atlas_w, atlas_h, len(CHARS), cell_w, cell_h))


# ---------------------------------------------------------------------------
# Icons: 24 cells of 64x64 in a 6x4 sheet, drawn at 4x and downsampled
# ---------------------------------------------------------------------------
ICON = 64
SS = 4                      # supersampling factor
S = ICON * SS               # drawing space of a single icon
ICON_COLS = 6
ICONS = [
    "home", "search", "library", "heart", "heart_filled", "play",
    "pause", "next", "prev", "shuffle", "repeat", "settings",
    "close", "volume", "volume_muted", "plus", "note", "check",
    "chevron_left", "chevron_right", "list", "link", "wifi", "globe",
]


def _canvas() -> tuple[Image.Image, ImageDraw.ImageDraw]:
    img = Image.new("RGBA", (S, S), (255, 255, 255, 0))
    return img, ImageDraw.Draw(img)


class Pen:
    """Draws in a virtual 64x64 icon space onto a supersampled canvas."""

    def __init__(self, draw: ImageDraw.ImageDraw):
        self.d = draw

    @staticmethod
    def _p(points):
        return [(x * SS, y * SS) for (x, y) in points]

    def line(self, points, width=3.0, colour=(255, 255, 255, 255), closed=False):
        pts = self._p(points + ([points[0]] if closed else []))
        w = max(1, int(width * SS))
        self.d.line(pts, fill=colour, width=w, joint="curve")
        # round caps so strokes look like a vector icon
        r = w / 2.0
        for (x, y) in pts:
            self.d.ellipse([x - r, y - r, x + r, y + r], fill=colour)

    def poly(self, points, colour=(255, 255, 255, 255)):
        self.d.polygon(self._p(points), fill=colour)

    def circle(self, cx, cy, r, colour=(255, 255, 255, 255), stroke=0.0):
        box = [(cx - r) * SS, (cy - r) * SS, (cx + r) * SS, (cy + r) * SS]
        if stroke > 0:
            self.d.ellipse(box, outline=colour, width=max(1, int(stroke * SS)))
        else:
            self.d.ellipse(box, fill=colour)

    def rect(self, x0, y0, x1, y1, radius=2.0, colour=(255, 255, 255, 255), stroke=0.0):
        box = [x0 * SS, y0 * SS, x1 * SS, y1 * SS]
        r = radius * SS
        if stroke > 0:
            self.d.rounded_rectangle(box, radius=r, outline=colour, width=max(1, int(stroke * SS)))
        else:
            self.d.rounded_rectangle(box, radius=r, fill=colour)

    def arc(self, cx, cy, r, start, end, width=3.0, colour=(255, 255, 255, 255)):
        box = [(cx - r) * SS, (cy - r) * SS, (cx + r) * SS, (cy + r) * SS]
        self.d.arc(box, start, end, fill=colour, width=max(1, int(width * SS)))

    def clear_poly(self, points):
        self.d.polygon(self._p(points), fill=(255, 255, 255, 0))

    def clear_circle(self, cx, cy, r):
        self.d.ellipse([(cx - r) * SS, (cy - r) * SS, (cx + r) * SS, (cy + r) * SS], fill=(255, 255, 255, 0))


def draw_icon(name: str) -> Image.Image:
    img, d = _canvas()
    p = Pen(d)
    W = 3.4

    if name == "home":
        p.line([(32, 15), (13, 32)], W)
        p.line([(32, 15), (51, 32)], W)
        p.line([(19, 31), (19, 49), (45, 49), (45, 31)], W)
    elif name == "search":
        p.circle(29, 28, 13, stroke=W)
        p.line([(39, 39), (50, 50)], W)
    elif name == "library":
        p.rect(16, 20, 21, 48, 1.4)
        p.rect(27, 16, 32, 48, 1.4)
        p.line([(42, 19), (47, 47)], W + 0.6)
    elif name in ("heart", "heart_filled"):
        filled = name == "heart_filled"
        colour = (255, 255, 255, 255)
        if filled:
            p.circle(24, 25, 9)
            p.circle(40, 25, 9)
            p.poly([(16, 27), (48, 27), (32, 50)])
        else:
            # filled heart, then punch out a smaller heart to get a clean outline
            p.circle(24, 25, 9)
            p.circle(40, 25, 9)
            p.poly([(16, 27), (48, 27), (32, 50)])
            p.clear_circle(24, 24.4, 6.0)
            p.clear_circle(40, 24.4, 6.0)
            p.clear_poly([(20.5, 25.6), (43.5, 25.6), (32, 43.5)])
    elif name == "play":
        p.poly([(24, 15), (24, 49), (49, 32)])
    elif name == "pause":
        p.rect(21, 16, 28, 48, 1.6)
        p.rect(36, 16, 43, 48, 1.6)
    elif name == "next":
        p.poly([(17, 16), (17, 48), (38, 32)])
        p.rect(41, 16, 47, 48, 1.6)
    elif name == "prev":
        p.poly([(47, 16), (47, 48), (26, 32)])
        p.rect(17, 16, 23, 48, 1.6)
    elif name == "shuffle":
        p.line([(14, 21), (24, 21), (41, 43), (48, 43)], 2.6)
        p.line([(14, 43), (24, 43), (41, 21), (48, 21)], 2.6)
        p.poly([(45, 16), (45, 26), (52, 21)])
        p.poly([(45, 38), (45, 48), (52, 43)])
    elif name == "repeat":
        p.line([(20, 20), (42, 20), (42, 27)], 2.8)
        p.line([(44, 44), (22, 44), (22, 37)], 2.8)
        p.poly([(16, 32), (27, 27), (27, 37)])
        p.poly([(48, 32), (37, 27), (37, 37)])
    elif name == "settings":
        import math
        cx, cy = 32.0, 32.0
        for i in range(8):
            a = (i / 8.0) * math.tau
            # thick radial tooth
            p.line([(cx + math.cos(a) * 12.0, cy + math.sin(a) * 12.0),
                    (cx + math.cos(a) * 19.0, cy + math.sin(a) * 19.0)], 6.4)
        p.circle(cx, cy, 13.6, stroke=5.0)
        p.clear_circle(cx, cy, 6.0)
    elif name == "close":
        p.line([(20, 20), (44, 44)], W)
        p.line([(44, 20), (20, 44)], W)
    elif name in ("volume", "volume_muted"):
        p.poly([(15, 26), (23, 26), (32, 17), (32, 47), (23, 38), (15, 38)])
        if name == "volume":
            p.arc(32, 32, 12, -55, 55, 2.6)
            p.arc(32, 32, 19, -50, 50, 2.4)
        else:
            p.line([(40, 26), (50, 38)], 2.8)
            p.line([(50, 26), (40, 38)], 2.8)
    elif name == "plus":
        p.line([(32, 17), (32, 47)], W)
        p.line([(17, 32), (47, 32)], W)
    elif name == "note":
        p.rect(36, 14, 43, 38, 1.2)
        p.circle(30, 42, 8)
        p.line([(39, 16), (39, 42)], 2.4)
    elif name == "check":
        p.line([(17, 33), (28, 44), (47, 20)], W)
    elif name == "chevron_left":
        p.line([(38, 18), (24, 32), (38, 46)], W)
    elif name == "chevron_right":
        p.line([(26, 18), (40, 32), (26, 46)], W)
    elif name == "list":
        for y in (20, 32, 44):
            p.circle(16, y, 2.6)
            p.rect(25, y - 2.4, 50, y + 2.4, 1.2)
    elif name == "link":
        p.rect(12, 24, 37, 40, 7, stroke=2.8)
        p.rect(27, 24, 52, 40, 7, stroke=2.8)
    elif name == "wifi":
        p.arc(32, 44, 22, 200, 340, 3.0)
        p.arc(32, 44, 14, 202, 338, 3.0)
        p.circle(32, 46, 3.4)
    elif name == "globe":
        p.circle(32, 32, 19, stroke=2.8)
        p.line([(13, 32), (51, 32)], 2.4)
        p.d.ellipse([(32 - 9) * SS, 13 * SS, (32 + 9) * SS, 51 * SS],
                    outline=(255, 255, 255, 255), width=int(2.4 * SS))
    else:
        raise SystemExit("unknown icon: " + name)

    return img.resize((ICON, ICON), Image.LANCZOS)


def build_icons() -> None:
    rows = (len(ICONS) + ICON_COLS - 1) // ICON_COLS
    sheet = Image.new("RGBA", (ICON_COLS * ICON, rows * ICON), (255, 255, 255, 0))
    for index, name in enumerate(ICONS):
        icon = draw_icon(name)
        sheet.paste(icon, ((index % ICON_COLS) * ICON, (index // ICON_COLS) * ICON))
    sheet.save(os.path.join(TEX, "icons.png"))
    print("icons.png     %dx%d  (%d icons)" % (sheet.width, sheet.height, len(ICONS)))
    with open(os.path.join(ASSETS, "gui", "icons.txt"), "w", encoding="utf-8") as fh:
        fh.write("# MC Music icon sheet - generated by tools/gen_ui_assets.py\n")
        fh.write("size=%d\ncolumns=%d\n" % (ICON, ICON_COLS))
        for index, name in enumerate(ICONS):
            fh.write("%d %s\n" % (index, name))


# ---------------------------------------------------------------------------
# Rounded corner mask (top left quarter of a filled rounded rectangle)
# ---------------------------------------------------------------------------
def build_corner() -> None:
    size = 128
    big = Image.new("L", (size * 4, size * 4), 0)
    d = ImageDraw.Draw(big)
    r = size * 4
    d.ellipse([0, 0, r * 2 - 1, r * 2 - 1], fill=255)          # round outer corner
    d.rectangle([r, 0, r * 2, r * 2], fill=255)                  # square it off
    d.rectangle([0, r, r * 2, r * 2], fill=255)
    small = big.resize((size, size), Image.LANCZOS)
    out = Image.new("RGBA", (size, size), (255, 255, 255, 0))
    out.putalpha(small)
    out.paste((255, 255, 255, 255), (0, 0), small)
    out.save(os.path.join(TEX, "corner.png"))
    print("corner.png    %dx%d" % (size, size))


# ---------------------------------------------------------------------------
# Soft shadow / glow corner
# ---------------------------------------------------------------------------
def build_corner_inverse() -> None:
    """Opaque everywhere except a quarter circle - used to mask picture corners."""
    size = 128
    big = Image.new("L", (size * 4, size * 4), 255)
    d = ImageDraw.Draw(big)
    r = size * 4
    d.ellipse([0, 0, r * 2 - 1, r * 2 - 1], fill=0)
    small = big.resize((size, size), Image.LANCZOS)
    out = Image.new("RGBA", (size, size), (255, 255, 255, 0))
    out.putalpha(small)
    out.paste((255, 255, 255, 255), (0, 0), small)
    out.save(os.path.join(TEX, "corner_inv.png"))
    print("corner_inv.png %dx%d" % (size, size))


def write_font_java(cell_w, cell_h, atlas_w, atlas_h, left, top, pad, metrics) -> None:
    """Emits the metrics as a Java class so no file parsing is needed at runtime."""
    advances = []
    for code, advance, _col, _row in metrics:
        advances.append(int(round(advance * 4)))  # quarter pixel precision

    out = os.path.join(ROOT, "src", "main", "java", "de", "chaostobimc", "mcmusic", "client", "ui", "FontMetrics.java")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w", encoding="utf-8") as fh:
        fh.write("package de.chaostobimc.mcmusic.client.ui;\n\n")
        fh.write("/**\n * Glyph metrics for the UI font atlas.\n *\n")
        fh.write(" * <p>Generated by {@code tools/gen_ui_assets.py} - do not edit by hand.</p>\n */\n")
        fh.write("public final class FontMetrics {\n\n")
        fh.write("    private FontMetrics() {\n    }\n\n")
        fh.write("    public static final int ATLAS_WIDTH = %d;\n" % atlas_w)
        fh.write("    public static final int ATLAS_HEIGHT = %d;\n" % atlas_h)
        fh.write("    public static final int CELL_WIDTH = %d;\n" % cell_w)
        fh.write("    public static final int CELL_HEIGHT = %d;\n" % cell_h)
        fh.write("    public static final int COLUMNS = %d;\n" % COLS)
        fh.write("    public static final int GLYPH_SIZE = %d;\n" % GLYPH_PX)
        fh.write("    public static final int ORIGIN_X = %d;\n" % (-(pad - left)))
        fh.write("    public static final int ORIGIN_Y = %d;\n" % (-(pad - top)))
        fh.write("    public static final int LINE_HEIGHT = %d;\n\n" % int(round(GLYPH_PX * 1.32)))
        fh.write("    /** Characters after ASCII and Latin-1 that are packed into the atlas. */\n")
        fh.write("    public static final String SPECIALS = \"%s\";\n\n" % SPECIAL)
        fh.write("    /** Advance width in 1/4 atlas pixels, one entry per glyph. */\n")
        fh.write("    public static final short[] ADVANCE_Q4 = {\n")
        for i in range(0, len(advances), 16):
            chunk = ", ".join(str(v) for v in advances[i:i + 16])
            fh.write("            %s,\n" % chunk)
        fh.write("    };\n}\n")
    print("FontMetrics.java  %d glyphs" % len(advances))


def build_shadow() -> None:
    size = 128
    big = Image.new("L", (size * 4, size * 4), 0)
    d = ImageDraw.Draw(big)
    r = size * 4
    d.ellipse([0, 0, r * 2 - 1, r * 2 - 1], fill=255)
    d.rectangle([r, 0, r * 2, r * 2], fill=255)
    d.rectangle([0, r, r * 2, r * 2], fill=255)
    big = big.resize((size, size), Image.LANCZOS).filter(ImageFilter.GaussianBlur(14))
    out = Image.new("RGBA", (size, size), (255, 255, 255, 0))
    out.paste((255, 255, 255, 255), (0, 0), big)
    out.save(os.path.join(TEX, "shadow.png"))
    print("shadow.png    %dx%d" % (size, size))


# ---------------------------------------------------------------------------
# Mod icon
# ---------------------------------------------------------------------------
def build_mod_icon() -> None:
    size = 128
    big = Image.new("RGBA", (size * 4, size * 4), (0, 0, 0, 0))
    d = ImageDraw.Draw(big)
    d.rounded_rectangle([0, 0, size * 4 - 1, size * 4 - 1], radius=26 * 4, fill=(255, 0, 51, 255))
    # vertical gradient overlay
    grad = Image.new("RGBA", (size * 4, size * 4), (0, 0, 0, 0))
    gd = ImageDraw.Draw(grad)
    for y in range(size * 4):
        alpha = int(70 * (1 - y / (size * 4)))
        gd.line([(0, y), (size * 4, y)], fill=(0, 0, 0, alpha))
    big.alpha_composite(grad)
    note = draw_icon("note").resize((int(size * 4 * 0.62), int(size * 4 * 0.62)), Image.LANCZOS)
    big.alpha_composite(note, (int(size * 4 * 0.19), int(size * 4 * 0.19)))
    big.resize((size, size), Image.LANCZOS).save(os.path.join(ASSETS, "icon.png"))
    print("icon.png      %dx%d" % (size, size))


def main() -> None:
    os.makedirs(TEX, exist_ok=True)
    os.makedirs(os.path.join(ASSETS, "gui"), exist_ok=True)
    build_font()
    build_icons()
    build_corner()
    build_corner_inverse()
    build_shadow()
    build_mod_icon()


if __name__ == "__main__":
    main()
